function emitTextStylesFile(
  textStyles: ReadonlyArray<PreparedComposeTextStyle | unknown>,
  packagePath: string,
  packageName: string,
): EmittedFile {
  const lines: string[] = [
    '// GENERATED FILE — do not edit by hand.',
    '// Generated by Varcast.',
    '',
    `package ${packageName}.composites`,
    '',
    'import androidx.compose.runtime.Immutable',
    'import androidx.compose.ui.text.TextStyle',
    'import androidx.compose.ui.text.font.FontFamily',
    'import androidx.compose.ui.text.font.FontWeight',
    'import androidx.compose.ui.unit.sp',
    '',
  ];

  if (textStyles.length === 0) {
    lines.push('@Immutable');
    lines.push('object DSTextStyles');
    lines.push('');
  } else {
    lines.push('@Immutable');
    lines.push('object DSTextStyles {');

    for (let i = 0; i < textStyles.length; i++) {
      const s = textStyles[i];
      const prop = extractGetterName(s, `textStyle${i + 1}`);
      const fontSize = extractFontSize(s);
      const fontWeight = extractFontWeight(s);
      const lineHeight = extractLineHeight(s, fontSize);
      const letterSpacing = extractLetterSpacing(s, fontSize);

      lines.push(`    val ${prop}: TextStyle = TextStyle(`);
      lines.push(`        fontSize = ${formatNumber(fontSize)}.sp,`);
      lines.push(`        fontWeight = FontWeight(${fontWeight}),`);
      lines.push(`        lineHeight = ${formatNumber(lineHeight)}.sp,`);
      lines.push(`        letterSpacing = ${formatNumber(letterSpacing)}.sp,`);
      lines.push('        fontFamily = FontFamily.Default,');
      lines.push('    )');
    }

    lines.push('}');
    lines.push('');
  }

  return {
    path: `src/main/kotlin/${packagePath}/composites/TextStyles.kt`,
    contents: lines.join('\n'),
  };
}

