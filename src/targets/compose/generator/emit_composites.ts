function emitShadowsFile(
  effectStyles: ReadonlyArray<PreparedComposeEffectStyle | unknown>,
  packagePath: string,
  packageName: string,
): EmittedFile {
  const lines: string[] = [
    '// GENERATED FILE — do not edit by hand.',
    '// Generated by Varcast.',
    '',
    `package ${packageName}.composites`,
    '',
    'import androidx.compose.runtime.Immutable',
    'import androidx.compose.ui.Modifier',
    'import androidx.compose.ui.draw.drawBehind',
    'import androidx.compose.ui.graphics.Color',
    'import androidx.compose.ui.graphics.Paint',
    'import androidx.compose.ui.graphics.drawscope.drawIntoCanvas',
    'import androidx.compose.ui.graphics.toArgb',
    'import androidx.compose.ui.unit.Dp',
    'import androidx.compose.ui.unit.dp',
    '',
    '@Immutable',
    'data class ShadowToken(',
    '    val color: Color,',
    '    val offsetX: Dp,',
    '    val offsetY: Dp,',
    '    val blurRadius: Dp,',
    '    val spread: Dp = 0.dp,',
    ')',
    '',
    'fun Modifier.dropShadow(',
    '    token: ShadowToken,',
    '): Modifier = this.drawBehind {',
    '    drawIntoCanvas { canvas ->',
    '        val paint = Paint()',
    '        val frameworkPaint = paint.asFrameworkPaint()',
    '        frameworkPaint.color = token.color.toArgb()',
    '        frameworkPaint.setShadowLayer(',
    '            token.blurRadius.toPx(),',
    '            token.offsetX.toPx(),',
    '            token.offsetY.toPx(),',
    '            token.color.toArgb(),',
    '        )',
    '        canvas.drawRect(',
    '            0f,',
    '            0f,',
    '            size.width,',
    '            size.height,',
    '            paint,',
    '        )',
    '    }',
    '}',
    '',
  ];

  if (effectStyles.length === 0) {
    lines.push('@Immutable');
    lines.push('object DSShadows');
    lines.push('');
  } else {
    lines.push('@Immutable');
    lines.push('object DSShadows {');

    for (let i = 0; i < effectStyles.length; i++) {
      const s = effectStyles[i];
      const prop = extractGetterName(s, `shadow${i + 1}`);
      const colorExpr = extractColorExpr(s);
      const offsetX = extractOffset(s, 'x');
      const offsetY = extractOffset(s, 'y');
      const blurRadius = extractBlurRadius(s);
      const spread = extractSpread(s);

      lines.push(`    val ${prop}: ShadowToken = ShadowToken(`);
      lines.push(`        color = ${colorExpr},`);
      lines.push(`        offsetX = ${formatNumber(offsetX)}.dp,`);
      lines.push(`        offsetY = ${formatNumber(offsetY)}.dp,`);
      lines.push(`        blurRadius = ${formatNumber(blurRadius)}.dp,`);
      lines.push(`        spread = ${formatNumber(spread)}.dp,`);
      lines.push('    )');
    }

    lines.push('}');
    lines.push('');
  }

  return {
    path: `src/main/kotlin/${packagePath}/composites/Shadows.kt`,
    contents: lines.join('\n'),
  };
}

// ============================================================================
// Helper Functions
// ============================================================================

function extractGetterName(item: unknown, fallback: string): string {
  if (!item || typeof item !== 'object') return fallback;
  const obj = item as Record<string, unknown>;
  if (typeof obj.getterName === 'string' && obj.getterName.trim().length > 0) {
    return safeProp(obj.getterName.trim());
  }
  return fallback;
}

function safeProp(prop: string): string {
  if (prop.startsWith('`') && prop.endsWith('`')) {
    return prop;
  }
  return escapeKotlinIdentifier(prop);
}

function extractPaintType(item: unknown): string {
  if (!item || typeof item !== 'object') return 'SOLID';
  const obj = item as Record<string, unknown>;
  if (typeof obj.type === 'string') return obj.type;
  const raw = obj.raw as IRPaintStyle | undefined;
  if (raw && typeof raw.type === 'string') return raw.type;
  return 'SOLID';
}

function extractAngleRadians(item: unknown): number {
  if (!item || typeof item !== 'object') return 0;
  const obj = item as Record<string, unknown>;
  if (typeof obj.angleRadians === 'number') {
    return obj.angleRadians;
  }
  const raw = obj.raw as { angleRadians?: number } | undefined;
  if (typeof raw?.angleRadians === 'number') {
    return raw.angleRadians;
  }
  return 0;
}

interface ExtractedStop {
  position: number;
  colorExpr: string;
}

function extractStops(item: unknown): ExtractedStop[] {
  if (!item || typeof item !== 'object') {
    return defaultStops();
  }

  const obj = item as Record<string, unknown>;

  // 1. Direct stops array (mock or explicit)
  if (Array.isArray(obj.stops) && obj.stops.length > 0) {
    return obj.stops.map((s: unknown) => extractSingleStop(s));
  }

  // 2. Resolved valuesByMode
  const resolved = obj.resolved as
    | {
        valuesByMode?: Record<
          string,
          {
            stops?: Array<{
              position: number;
              rgba?: RGBAValue | null;
              hex?: string | null;
            }>;
          }
        >;
      }
    | undefined;
  if (resolved?.valuesByMode) {
    for (const mv of Object.values(resolved.valuesByMode)) {
      if (Array.isArray(mv?.stops) && mv.stops.length > 0) {
        return mv.stops.map((s) => extractSingleStop(s));
      }
    }
  }

  // 3. Raw stops
  const raw = obj.raw as { stops?: IRGradientStop[] } | undefined;
  if (Array.isArray(raw?.stops) && raw.stops.length > 0) {
    return raw.stops.map((s) => extractSingleStop(s));
  }

  return defaultStops();
}

function extractSingleStop(stopItem: unknown): ExtractedStop {
  if (!stopItem || typeof stopItem !== 'object') {
    return { position: 0, colorExpr: 'Color(0x00000000UL)' };
  }
  const s = stopItem as Record<string, unknown>;
  const position = typeof s.position === 'number' ? s.position : 0;
  const colorExpr = extractColorExpr(s);
  return { position, colorExpr };
}

function defaultStops(): ExtractedStop[] {
  return [
    { position: 0, colorExpr: 'Color(0x00000000UL)' },
    { position: 1, colorExpr: 'Color(0x00000000UL)' },
  ];
}

function extractColorExpr(item: unknown): string {
  if (!item || typeof item !== 'object') {
    return 'Color(0x00000000UL)';
  }

  const obj = item as Record<string, unknown>;

  // 1. Direct mock/explicit colorExpr
  if (typeof obj.colorExpr === 'string') {
    return normalizeColorExpr(obj.colorExpr);
  }

  // 2. Direct rgba on item
  if (isRgbaObject(obj.rgba)) {
    return `Color(0x${rgbaToArgbHex(obj.rgba)}UL)`;
  }

  // 3. Check resolved valuesByMode
  const resolved = obj.resolved as
    | {
        valuesByMode?: Record<
          string,
          {
            rgba?: RGBAValue | null;
            hex?: string | null;
            shadowColor?: string | null;
          }
        >;
      }
    | undefined;
  if (resolved?.valuesByMode) {
    const modeValues = Object.values(resolved.valuesByMode);
    for (const mv of modeValues) {
      if (mv?.rgba && isRgbaObject(mv.rgba)) {
        return `Color(0x${rgbaToArgbHex(mv.rgba)}UL)`;
      }
      if (mv?.hex) {
        return hexStringToComposeColor(mv.hex);
      }
      if (mv?.shadowColor) {
        return hexStringToComposeColor(mv.shadowColor);
      }
    }
  }

  // 4. Direct valuesByMode on item
  const valuesByMode = obj.valuesByMode as
    | Record<
        string,
        {
          rgba?: RGBAValue | null;
          hex?: string | null;
          shadowColor?: string | null;
        }
      >
    | undefined;
  if (valuesByMode) {
    const modeValues = Object.values(valuesByMode);
    for (const mv of modeValues) {
      if (mv?.rgba && isRgbaObject(mv.rgba)) {
        return `Color(0x${rgbaToArgbHex(mv.rgba)}UL)`;
      }
      if (mv?.hex) {
        return hexStringToComposeColor(mv.hex);
      }
      if (mv?.shadowColor) {
        return hexStringToComposeColor(mv.shadowColor);
      }
    }
  }

  // 5. Raw color
  const raw = obj.raw as { color?: IRColorValue } | undefined;
  if (raw?.color) {
    if (raw.color.kind === 'literal' && isRgbaObject(raw.color.rgba)) {
      return `Color(0x${rgbaToArgbHex(raw.color.rgba)}UL)`;
    }
  }

  // 6. Direct color property on item
  const directColor = obj.color as
    | IRColorValue
    | { r: number; g: number; b: number; a?: number }
    | undefined;
  if (directColor) {
    if (isRgbaObject(directColor)) {
      return `Color(0x${rgbaToArgbHex(directColor)}UL)`;
    }
    if (directColor.kind === 'literal' && isRgbaObject(directColor.rgba)) {
      return `Color(0x${rgbaToArgbHex(directColor.rgba)}UL)`;
    }
  }

  // 7. Direct hex property
  if (typeof obj.hex === 'string') {
    return hexStringToComposeColor(obj.hex);
  }

  return 'Color(0x00000000UL)';
}

function normalizeColorExpr(expr: string): string {
  const trimmed = expr.trim();
  if (trimmed.startsWith('Color(') && trimmed.endsWith(')')) {
    const inner = trimmed.slice(6, -1).trim();
    if (inner.startsWith('0x') || inner.startsWith('0X')) {
      const hexPart = inner.slice(2).replace(/[uUlL]+$/, '');
      return `Color(0x${hexPart.toUpperCase()}UL)`;
    }
    return trimmed;
  }
  if (trimmed.startsWith('#')) {
    return hexStringToComposeColor(trimmed);
  }
  if (trimmed.startsWith('0x') || trimmed.startsWith('0X')) {
    const hexPart = trimmed.slice(2).replace(/[uUlL]+$/, '');
    return `Color(0x${hexPart.toUpperCase()}UL)`;
  }
  return trimmed;
}

function hexStringToComposeColor(hexStr: string): string {
  const clean = hexStr.replace(/^#/, '');
  if (clean.length === 6) {
    return `Color(0xFF${clean.toUpperCase()}UL)`;
  }
  if (clean.length === 8) {
    const rrggbb = clean.slice(0, 6).toUpperCase();
    const aa = clean.slice(6, 8).toUpperCase();
    return `Color(0x${aa}${rrggbb}UL)`;
  }
  return 'Color(0x00000000UL)';
}

function rgbaToArgbHex(rgba: {
  r: number;
  g: number;
  b: number;
  a?: number;
}): string {
  const clamp = (n: number) => (n < 0 ? 0 : n > 1 ? 1 : n);
  const a = rgba.a !== undefined ? clamp(rgba.a) : 1;
  const r = clamp(rgba.r);
  const g = clamp(rgba.g);
  const b = clamp(rgba.b);

  const hex2 = (n: number) =>
    Math.round(n * 255)
      .toString(16)
      .padStart(2, '0')
      .toUpperCase();

  return `${hex2(a)}${hex2(r)}${hex2(g)}${hex2(b)}`;
}

function isRgbaObject(
  v: unknown,
): v is { r: number; g: number; b: number; a?: number } {
  return (
    typeof v === 'object' &&
    v !== null &&
    'r' in v &&
    'g' in v &&
    'b' in v &&
    typeof (v as { r: unknown }).r === 'number'
  );
}

function formatFloat(n: number): string {
  if (!Number.isFinite(n)) return '0f';
  const rounded = Math.round(n * 10000) / 10000;
  const normalized = Object.is(rounded, -0) ? 0 : rounded;
  return `${normalized}f`;
}

function formatNumber(n: number): string {
  if (!Number.isFinite(n)) return '0';
  const rounded = Math.round(n * 10000) / 10000;
  return Object.is(rounded, -0) ? '0' : String(rounded);
}

function extractFontSize(item: unknown): number {
  if (!item || typeof item !== 'object') return 16;
  const obj = item as Record<string, unknown>;
  if (typeof obj.fontSizeSp === 'number') return obj.fontSizeSp;
  if (typeof obj.fontSize === 'number') return obj.fontSize;

  const resolved = obj.resolved as
    | { valuesByMode?: Record<string, { fontSize?: number | null }> }
    | undefined;
  if (resolved?.valuesByMode) {
    for (const mv of Object.values(resolved.valuesByMode)) {
      if (typeof mv?.fontSize === 'number') return mv.fontSize;
    }
  }

  const raw = obj.raw as
    | { fontSize?: { kind: string; value: number } }
    | undefined;
  if (
    raw?.fontSize?.kind === 'literal' &&
    typeof raw.fontSize.value === 'number'
  ) {
    return raw.fontSize.value;
  }

  return 16;
}

function extractFontWeight(item: unknown): number {
  if (!item || typeof item !== 'object') return 400;
  const obj = item as Record<string, unknown>;
  if (typeof obj.fontWeight === 'number') return obj.fontWeight;
  if (typeof obj.fontWeight === 'string') return parseWeight(obj.fontWeight);

  const resolved = obj.resolved as
    | {
        valuesByMode?: Record<
          string,
          { fontWeight?: string | number | null }
        >;
      }
    | undefined;
  if (resolved?.valuesByMode) {
    for (const mv of Object.values(resolved.valuesByMode)) {
      if (typeof mv?.fontWeight === 'number') return mv.fontWeight;
      if (typeof mv?.fontWeight === 'string') return parseWeight(mv.fontWeight);
    }
  }

  const raw = obj.raw as
    | { fontWeight?: { kind: string; value: number } }
    | undefined;
  if (
    raw?.fontWeight?.kind === 'literal' &&
    typeof raw.fontWeight.value === 'number'
  ) {
    return raw.fontWeight.value;
  }

  return 400;
}

function parseWeight(str: string): number {
  const parsed = parseInt(str, 10);
  if (!Number.isNaN(parsed) && parsed >= 100 && parsed <= 1000) {
    return parsed;
  }
  const lower = str.toLowerCase();
  if (lower.includes('thin')) return 100;
  if (lower.includes('extra') && lower.includes('light')) return 200;
  if (lower.includes('light')) return 300;
  if (lower.includes('medium')) return 500;
  if (lower.includes('semi') || lower.includes('demi')) return 600;
  if (lower.includes('bold')) return 700;
  if (lower.includes('black') || lower.includes('heavy')) return 900;
  return 400;
}

function extractLineHeight(item: unknown, fontSize: number): number {
  if (!item || typeof item !== 'object') {
    return Math.round(fontSize * 1.2 * 100) / 100;
  }
  const obj = item as Record<string, unknown>;
  if (typeof obj.lineHeightSp === 'number') return obj.lineHeightSp;
  if (typeof obj.lineHeight === 'number') return obj.lineHeight;

  const resolved = obj.resolved as
    | {
        valuesByMode?: Record<
          string,
          {
            lineHeight?: {
              value: number;
              unit: 'PIXELS' | 'PERCENT' | 'AUTO';
            } | null;
          }
        >;
      }
    | undefined;
  if (resolved?.valuesByMode) {
    for (const mv of Object.values(resolved.valuesByMode)) {
      if (mv?.lineHeight) {
        if (mv.lineHeight.unit === 'PERCENT') {
          return (
            Math.round(fontSize * (mv.lineHeight.value / 100) * 100) / 100
          );
        }
        if (mv.lineHeight.unit === 'PIXELS') {
          return mv.lineHeight.value;
        }
      }
    }
  }

  const raw = obj.raw as
    | {
        lineHeight?: {
          kind: string;
          value: number;
          unit: 'PIXELS' | 'PERCENT' | 'AUTO';
        };
      }
    | undefined;
  if (raw?.lineHeight?.kind === 'literal') {
    if (raw.lineHeight.unit === 'PERCENT') {
      return Math.round(fontSize * (raw.lineHeight.value / 100) * 100) / 100;
    }
    if (raw.lineHeight.unit === 'PIXELS') {
      return raw.lineHeight.value;
    }
  }

  return Math.round(fontSize * 1.2 * 100) / 100;
}

function extractLetterSpacing(item: unknown, fontSize: number): number {
  if (!item || typeof item !== 'object') return 0;
  const obj = item as Record<string, unknown>;
  if (typeof obj.letterSpacingSp === 'number') return obj.letterSpacingSp;
  if (typeof obj.letterSpacing === 'number') return obj.letterSpacing;

  const resolved = obj.resolved as
    | {
        valuesByMode?: Record<
          string,
          {
            letterSpacing?: {
              value: number;
              unit: 'PIXELS' | 'PERCENT' | 'AUTO';
            } | null;
          }
        >;
      }
    | undefined;
  if (resolved?.valuesByMode) {
    for (const mv of Object.values(resolved.valuesByMode)) {
      if (mv?.letterSpacing) {
        if (mv.letterSpacing.unit === 'PERCENT') {
          return (
            Math.round(((fontSize * mv.letterSpacing.value) / 100) * 100) / 100
          );
        }
        if (mv.letterSpacing.unit === 'PIXELS') {
          return mv.letterSpacing.value;
        }
      }
    }
  }

  const raw = obj.raw as
    | {
        letterSpacing?: {
          kind: string;
          value: number;
          unit: 'PIXELS' | 'PERCENT' | 'AUTO';
        };
      }
    | undefined;
  if (raw?.letterSpacing?.kind === 'literal') {
    if (raw.letterSpacing.unit === 'PERCENT') {
      return (
        Math.round(((fontSize * raw.letterSpacing.value) / 100) * 100) / 100
      );
    }
    if (raw.letterSpacing.unit === 'PIXELS') {
      return raw.letterSpacing.value;
    }
  }

  return 0;
}

function extractOffset(item: unknown, axis: 'x' | 'y'): number {
  if (!item || typeof item !== 'object') return 0;
  const obj = item as Record<string, unknown>;
  const key = axis === 'x' ? 'offsetX' : 'offsetY';
  if (typeof obj[key] === 'number') return obj[key] as number;

  const resolved = obj.resolved as
    | {
        valuesByMode?: Record<
          string,
          { offsetX?: number; offsetY?: number }
        >;
      }
    | undefined;
  if (resolved?.valuesByMode) {
    for (const mv of Object.values(resolved.valuesByMode)) {
      if (typeof mv?.[key] === 'number') return mv[key] as number;
    }
  }

  const raw = obj.raw as Record<string, unknown> | undefined;
  if (typeof raw?.[key] === 'number') return raw[key] as number;

  return 0;
}

function extractBlurRadius(item: unknown): number {
  if (!item || typeof item !== 'object') return 0;
  const obj = item as Record<string, unknown>;
  if (typeof obj.blurRadius === 'number') return obj.blurRadius;

  const resolved = obj.resolved as
    | { valuesByMode?: Record<string, { blurRadius?: number }> }
    | undefined;
  if (resolved?.valuesByMode) {
    for (const mv of Object.values(resolved.valuesByMode)) {
      if (typeof mv?.blurRadius === 'number') return mv.blurRadius;
    }
  }

  const raw = obj.raw as
    | { blurRadius?: number; sigmaX?: number; sigmaY?: number }
    | undefined;
  if (typeof raw?.blurRadius === 'number') return raw.blurRadius;
  if (typeof raw?.sigmaX === 'number') return raw.sigmaX;
  if (typeof raw?.sigmaY === 'number') return raw.sigmaY;

  return 0;
}

function extractSpread(item: unknown): number {
  if (!item || typeof item !== 'object') return 0;
  const obj = item as Record<string, unknown>;
  if (typeof obj.spread === 'number') return obj.spread;
  if (typeof obj.spreadRadius === 'number') return obj.spreadRadius;

  const resolved = obj.resolved as
    | { valuesByMode?: Record<string, { spread?: number }> }
    | undefined;
  if (resolved?.valuesByMode) {
    for (const mv of Object.values(resolved.valuesByMode)) {
      if (typeof mv?.spread === 'number') return mv.spread;
    }
  }

  const raw = obj.raw as { spreadRadius?: number } | undefined;
  if (typeof raw?.spreadRadius === 'number') return raw.spreadRadius;

  return 0;
}
