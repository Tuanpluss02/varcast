import type { EmittedFile } from '../../../core/target';
import type {
  IRColorValue,
  IRGradientStop,
  IRPaintStyle,
} from '../../../ir/types';
import type { RGBAValue } from '../../../core/graph/types';
import { escapeKotlinIdentifier } from '../identifier';
import type {
  PreparedCompose,
  PreparedComposeEffectStyle,
  PreparedComposePaintStyle,
  PreparedComposeTextStyle,
} from './prepare';

/**
 * Emits all Kotlin source files for Figma composite styles in Jetpack Compose:
 * - ColorStyles.kt (Brushes and SolidColor)
 * - TextStyles.kt (TextStyle)
 * - Shadows.kt (ShadowToken data class, modifier helper, and DSShadows)
 */
export function emitComposites(
  prepared: PreparedCompose,
  packagePath: string,
  packageName: string,
): EmittedFile[] {
  const cleanPackagePath = packagePath.replace(/^\/+|\/+$/g, '');
  const cleanPackageName = packageName.replace(/^\.+|\.+$/g, '');

  return [
    emitColorStylesFile(
      prepared.paintStyles ?? [],
      cleanPackagePath,
      cleanPackageName,
    ),
    emitTextStylesFile(
      prepared.textStyles ?? [],
      cleanPackagePath,
      cleanPackageName,
    ),
    emitShadowsFile(
      prepared.effectStyles ?? [],
      cleanPackagePath,
      cleanPackageName,
    ),
  ];
}

// ============================================================================
// 1. ColorStyles.kt
// ============================================================================

function emitColorStylesFile(
  paintStyles: ReadonlyArray<PreparedComposePaintStyle | unknown>,
  packagePath: string,
  packageName: string,
): EmittedFile {
  const lines: string[] = [
    '// GENERATED FILE — do not edit by hand.',
    '// Generated by Varcast.',
    '',
    `package ${packageName}.composites`,
    '',
    'import androidx.compose.runtime.Immutable',
    'import androidx.compose.ui.geometry.Offset',
    'import androidx.compose.ui.graphics.Brush',
    'import androidx.compose.ui.graphics.Color',
    'import androidx.compose.ui.graphics.SolidColor',
    '',
  ];

  if (paintStyles.length === 0) {
    lines.push('@Immutable');
    lines.push('object DSColorStyles');
    lines.push('');
  } else {
    lines.push('@Immutable');
    lines.push('object DSColorStyles {');

    for (let i = 0; i < paintStyles.length; i++) {
      const s = paintStyles[i];
      const prop = extractGetterName(s, `colorStyle${i + 1}`);
      const type = extractPaintType(s);

      switch (type) {
        case 'SOLID': {
          const colorExpr = extractColorExpr(s);
          lines.push(`    val ${prop}: SolidColor = SolidColor(${colorExpr})`);
          break;
        }
        case 'GRADIENT_LINEAR': {
          const stops = extractStops(s);
          const angle = extractAngleRadians(s);
          const cos = Math.cos(angle);
          const sin = Math.sin(angle);
          const startX = 0.5 - cos / 2;
          const startY = 0.5 - sin / 2;
          const endX = 0.5 + cos / 2;
          const endY = 0.5 + sin / 2;

          lines.push(`    val ${prop}: Brush = Brush.linearGradient(`);
          lines.push('        colorStops = arrayOf(');
          for (const stop of stops) {
            lines.push(
              `            ${formatFloat(stop.position)} to ${stop.colorExpr},`,
            );
          }
          lines.push('        ),');
          lines.push(
            `        start = Offset(${formatFloat(startX)}, ${formatFloat(startY)}),`,
          );
          lines.push(
            `        end = Offset(${formatFloat(endX)}, ${formatFloat(endY)}),`,
          );
          lines.push('    )');
          break;
        }
        case 'GRADIENT_RADIAL': {
          const stops = extractStops(s);
          lines.push(`    val ${prop}: Brush = Brush.radialGradient(`);
          lines.push('        colorStops = arrayOf(');
          for (const stop of stops) {
            lines.push(
              `            ${formatFloat(stop.position)} to ${stop.colorExpr},`,
            );
          }
          lines.push('        ),');
          lines.push('    )');
          break;
        }
        case 'GRADIENT_SWEEP':
        case 'GRADIENT_ANGULAR': {
          const stops = extractStops(s);
          lines.push(`    val ${prop}: Brush = Brush.sweepGradient(`);
          lines.push('        colorStops = arrayOf(');
          for (const stop of stops) {
            lines.push(
              `            ${formatFloat(stop.position)} to ${stop.colorExpr},`,
            );
          }
          lines.push('        ),');
          lines.push('    )');
          break;
        }
        case 'GRADIENT_DIAMOND': {
          const stops = extractStops(s);
          lines.push('    // Approximated from Figma GRADIENT_DIAMOND.');
          lines.push(`    val ${prop}: Brush = Brush.radialGradient(`);
          lines.push('        colorStops = arrayOf(');
          for (const stop of stops) {
            lines.push(
              `            ${formatFloat(stop.position)} to ${stop.colorExpr},`,
            );
          }
          lines.push('        ),');
          lines.push('    )');
          break;
        }
        default:
          lines.push(`    // Unsupported paint style type: ${type}`);
          break;
      }
    }

    lines.push('}');
    lines.push('');
  }

  return {
    path: `src/main/kotlin/${packagePath}/composites/ColorStyles.kt`,
    contents: lines.join('\n'),
  };
}

