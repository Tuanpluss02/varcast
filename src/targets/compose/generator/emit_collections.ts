import type { EmittedFile } from '../../../core/target';
import type { RGBA } from '../../../ir/types';
import type { ResolvedLiteral } from '../../../core/graph/types';
import { escapeKotlinIdentifier } from '../identifier';
import type {
  KotlinPrimitiveType,
  PreparedCompose,
  PreparedComposeCollection,
  PreparedComposeVariable,
} from './prepare';

/**
 * Emits all Kotlin source files for Figma variable collections in Jetpack Compose.
 */
export function emitCollections(
  prepared: PreparedCompose,
  packagePath: string,
  packageName: string,
): EmittedFile[] {
  const files: EmittedFile[] = [];

  for (const col of prepared.collections) {
    files.push(emitCollectionFile(col, packagePath, packageName));
  }

  return files;
}

function emitCollectionFile(
  col: PreparedComposeCollection,
  packagePath: string,
  packageName: string,
): EmittedFile {
  const cleanPackagePath = packagePath.replace(/^\/+|\/+$/g, '');
  const cleanPackageName = packageName.replace(/^\.+|\.+$/g, '');

  const hasColor = col.variables.some((v) => v.kotlinType === 'Color');
  const hasDp = col.variables.some((v) => v.kotlinType === 'Dp');
  const hasTextUnit = col.variables.some((v) => v.kotlinType === 'TextUnit');

  const imports = new Set<string>();
  imports.add('import androidx.compose.runtime.Immutable');

  if (hasColor) {
    imports.add('import androidx.compose.ui.graphics.Color');
    imports.add('import androidx.compose.ui.graphics.lerp as lerpColor');
  }
  if (hasDp) {
    imports.add('import androidx.compose.ui.unit.Dp');
    imports.add('import androidx.compose.ui.unit.dp');
    imports.add('import androidx.compose.ui.unit.lerp as lerpDp');
  }
  if (hasTextUnit) {
    imports.add('import androidx.compose.ui.unit.TextUnit');
    imports.add('import androidx.compose.ui.unit.lerp as lerpTextUnit');
    imports.add('import androidx.compose.ui.unit.sp');
  }

  const sortedImports = Array.from(imports).sort();

  const lines: string[] = [
    '// GENERATED FILE — do not edit by hand.',
    '// Generated by Varcast.',
    '',
    `package ${cleanPackageName}.collections`,
    '',
    ...sortedImports,
    '',
  ];

  const className = col.className;

  if (col.variables.length === 0) {
    lines.push('@Immutable');
    lines.push(`class ${className} {`);
    lines.push('    companion object {');
    lines.push(
      `        fun lerp(start: ${className}, stop: ${className}, fraction: Float): ${className} = start`,
    );
    lines.push('    }');
    lines.push('}');
  } else {
    lines.push('@Immutable');
    lines.push(`data class ${className}(`);
    for (const v of col.variables) {
      lines.push(`    val ${safeProp(v.propertyName)}: ${v.kotlinType},`);
    }
    lines.push(') {');
    lines.push('    companion object {');
    lines.push(
      `        fun lerp(start: ${className}, stop: ${className}, fraction: Float): ${className} = ${className}(`,
    );
    for (const v of col.variables) {
      const prop = safeProp(v.propertyName);
      lines.push(`            ${prop} = ${emitLerpExpr(v, prop)},`);
    }
    lines.push('        )');
    lines.push('    }');
    lines.push('}');
  }

  for (const mode of col.modes) {
    lines.push('');
    const modeValName = escapeKotlinIdentifier(`${mode.pascalName}${className}`);
    if (col.variables.length === 0) {
      lines.push(`val ${modeValName} = ${className}()`);
    } else {
      lines.push(`val ${modeValName} = ${className}(`);
      for (const v of col.variables) {
        const prop = safeProp(v.propertyName);
        const val = emitValue(v, mode.id);
        lines.push(`    ${prop} = ${val},`);
      }
      lines.push(')');
    }
  }

  lines.push('');

  return {
    path: `src/main/kotlin/${cleanPackagePath}/collections/${col.fileBaseName}.kt`,
    contents: lines.join('\n'),
  };
}

function emitLerpExpr(v: PreparedComposeVariable, prop: string): string {
  switch (v.kotlinType) {
    case 'Color':
      return `lerpColor(start.${prop}, stop.${prop}, fraction)`;
    case 'Dp':
      return `lerpDp(start.${prop}, stop.${prop}, fraction)`;
    case 'TextUnit':
      return `lerpTextUnit(start.${prop}, stop.${prop}, fraction)`;
    case 'Float':
      return `start.${prop} + (stop.${prop} - start.${prop}) * fraction`;
    case 'Boolean':
    case 'String':
      return `if (fraction < 0.5f) start.${prop} else stop.${prop}`;
  }
}

function emitValue(v: PreparedComposeVariable, modeId: string): string {
  const rawModeVal: unknown = v.valuesByMode?.[modeId];

  // Check if string is already a formatted code expression
  if (typeof rawModeVal === 'string') {
    if (
      v.kotlinType === 'Color' &&
      (rawModeVal.startsWith('Color(') || rawModeVal.startsWith('0x'))
    ) {
      return rawModeVal.startsWith('0x')
        ? `Color(${rawModeVal}${rawModeVal.endsWith('UL') ? '' : 'UL'})`
        : rawModeVal;
    }
    if (v.kotlinType === 'Dp' && rawModeVal.endsWith('.dp')) {
      return rawModeVal;
    }
    if (v.kotlinType === 'TextUnit' && rawModeVal.endsWith('.sp')) {
      return rawModeVal;
    }
    if (v.kotlinType === 'Float' && rawModeVal.endsWith('f')) {
      return rawModeVal;
    }
    if (
      v.kotlinType === 'Boolean' &&
      (rawModeVal === 'true' || rawModeVal === 'false')
    ) {
      return rawModeVal;
    }
  }

  // 1. Try pre-resolved value
  const preResolved = v.resolvedValuesByMode?.[modeId];
  if (preResolved !== undefined) {
    return formatResolvedLiteral(v.kotlinType, preResolved);
  }

  // 2. Check raw IRValue
  if (
    rawModeVal !== undefined &&
    typeof rawModeVal === 'object' &&
    rawModeVal !== null
  ) {
    if ('kind' in rawModeVal) {
      if (rawModeVal.kind === 'literal' && 'value' in rawModeVal) {
        return formatResolvedLiteral(v.kotlinType, rawModeVal.value);
      }
      return defaultExprFor(v.kotlinType);
    }
    if ('r' in rawModeVal && 'g' in rawModeVal && 'b' in rawModeVal) {
      return formatResolvedLiteral(v.kotlinType, rawModeVal);
    }
  }

  // 3. Raw primitive
  if (
    typeof rawModeVal === 'number' ||
    typeof rawModeVal === 'string' ||
    typeof rawModeVal === 'boolean'
  ) {
    return formatResolvedLiteral(v.kotlinType, rawModeVal);
  }

  return defaultExprFor(v.kotlinType);
}

function formatResolvedLiteral(
  type: KotlinPrimitiveType,
  val: ResolvedLiteral | RGBA | unknown,
): string {
  switch (type) {
    case 'Color': {
      if (
        typeof val === 'object' &&
        val !== null &&
        'r' in val &&
        'g' in val &&
        'b' in val
      ) {
        const rgba = val as { r: number; g: number; b: number; a?: number };
        return `Color(0x${rgbaToArgbHex(rgba)}UL)`;
      }
      if (typeof val === 'string') {
        if (val.startsWith('Color(')) return val;
        if (val.startsWith('#')) {
          return hexStringToComposeColor(val);
        }
        if (val.startsWith('0x')) {
          return `Color(${val}${val.endsWith('UL') ? '' : 'UL'})`;
        }
      }
      return defaultExprFor('Color');
    }
    case 'Dp': {
      if (typeof val === 'number') {
        return `${formatNumber(val)}.dp`;
      }
      if (typeof val === 'string') {
        if (val.endsWith('.dp')) return val;
        const parsed = Number(val);
        if (Number.isFinite(parsed)) return `${formatNumber(parsed)}.dp`;
      }
      return defaultExprFor('Dp');
    }
    case 'TextUnit': {
      if (typeof val === 'number') {
        return `${formatNumber(val)}.sp`;
      }
      if (typeof val === 'string') {
        if (val.endsWith('.sp')) return val;
        const parsed = Number(val);
        if (Number.isFinite(parsed)) return `${formatNumber(parsed)}.sp`;
      }
      return defaultExprFor('TextUnit');
    }
    case 'Float': {
      if (typeof val === 'number') {
        return `${formatNumber(val)}f`;
      }
      if (typeof val === 'string') {
        if (val.endsWith('f')) return val;
        const parsed = Number(val);
        if (Number.isFinite(parsed)) return `${formatNumber(parsed)}f`;
      }
      return defaultExprFor('Float');
    }
    case 'String': {
      const s = String(val ?? '');
      return JSON.stringify(s).replace(/\$/g, '\\$');
    }
    case 'Boolean': {
      return Boolean(val) ? 'true' : 'false';
    }
  }
}

function rgbaToArgbHex(rgba: {
  r: number;
  g: number;
  b: number;
  a?: number;
}): string {
  const clamp = (n: number) => (n < 0 ? 0 : n > 1 ? 1 : n);
  const a = rgba.a !== undefined ? clamp(rgba.a) : 1;
  const r = clamp(rgba.r);
  const g = clamp(rgba.g);
  const b = clamp(rgba.b);

  const hex2 = (n: number) =>
    Math.round(n * 255)
      .toString(16)
      .padStart(2, '0')
      .toUpperCase();

  return `${hex2(a)}${hex2(r)}${hex2(g)}${hex2(b)}`;
}

function hexStringToComposeColor(hexStr: string): string {
  const clean = hexStr.replace(/^#/, '');
  if (clean.length === 6) {
    return `Color(0xFF${clean.toUpperCase()}UL)`;
  }
  if (clean.length === 8) {
    const rrggbb = clean.slice(0, 6).toUpperCase();
    const aa = clean.slice(6, 8).toUpperCase();
    return `Color(0x${aa}${rrggbb}UL)`;
  }
  return defaultExprFor('Color');
}

function formatNumber(n: number): string {
  if (!Number.isFinite(n)) return '0';
  const rounded = Math.round(n * 1e6) / 1e6;
  return String(rounded);
}

function defaultExprFor(t: KotlinPrimitiveType): string {
  switch (t) {
    case 'Color':
      return 'Color(0x00000000UL)';
    case 'Dp':
      return '0.dp';
    case 'TextUnit':
      return '0.sp';
    case 'Float':
      return '0f';
    case 'String':
      return '""';
    case 'Boolean':
      return 'false';
  }
}

function safeProp(prop: string): string {
  if (prop.startsWith('`') && prop.endsWith('`')) {
    return prop;
  }
  return escapeKotlinIdentifier(prop);
}
