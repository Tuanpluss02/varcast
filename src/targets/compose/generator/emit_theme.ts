import type { EmittedFile } from '../../../core/target';
import { escapeKotlinIdentifier } from '../identifier';
import type { PreparedCompose, PreparedComposeCollection } from './prepare';

/**
 * Emits all Kotlin runtime and theming source files for Jetpack Compose:
 * - ThemeMode.kt (Per-collection mode enums)
 * - DesignSystemController.kt (Stateful controller tracking current modes and animating lerps)
 * - Theme.kt (CompositionLocal declarations, DesignSystemTheme composable & accessor object)
 * - AppTheme.kt (Static facade object for direct token access and runtime mode switching)
 */
export function emitTheme(
  prepared: PreparedCompose,
  packagePath: string,
  packageName: string,
): EmittedFile[] {
  const cleanPackagePath = packagePath.replace(/^\/+|\/+$/g, '');
  const cleanPackageName = packageName.replace(/^\.+|\.+$/g, '');
  const collections = prepared.collections ?? [];

  return [
    emitThemeModeFile(collections, cleanPackagePath, cleanPackageName),
    emitControllerFile(collections, cleanPackagePath, cleanPackageName),
    emitThemeFile(collections, cleanPackagePath, cleanPackageName),
    emitAppThemeFile(collections, cleanPackagePath, cleanPackageName),
  ];
}

// ============================================================================
// 1. ThemeMode.kt
// ============================================================================

function emitThemeModeFile(
  collections: ReadonlyArray<PreparedComposeCollection>,
  packagePath: string,
  packageName: string,
): EmittedFile {
  const lines: string[] = [
    '// GENERATED FILE — do not edit by hand.',
    '// Generated by Varcast.',
    '',
    `package ${packageName}.theme`,
    '',
  ];

  for (const col of collections) {
    lines.push(`enum class ${col.className}Mode {`);
    if (col.modes.length === 0) {
      lines.push('    Default,');
    } else {
      for (const mode of col.modes) {
        lines.push(`    ${escapeKotlinIdentifier(mode.pascalName)},`);
      }
    }
    lines.push('}');
    lines.push('');
  }

  return {
    path: `src/main/kotlin/${packagePath}/theme/ThemeMode.kt`,
    contents: lines.join('\n').trimEnd() + '\n',
  };
}

// ============================================================================
// 2. DesignSystemController.kt
// ============================================================================

function emitControllerFile(
  collections: ReadonlyArray<PreparedComposeCollection>,
  packagePath: string,
  packageName: string,
): EmittedFile {
  const lines: string[] = [
    '// GENERATED FILE — do not edit by hand.',
    '// Generated by Varcast.',
    '',
    `package ${packageName}.theme`,
    '',
  ];

  if (collections.length > 0) {
    lines.push('import androidx.compose.animation.core.Animatable');
    lines.push('import androidx.compose.animation.core.tween');
  }
  lines.push('import androidx.compose.runtime.getValue');
  lines.push('import androidx.compose.runtime.mutableIntStateOf');
  lines.push('import androidx.compose.runtime.mutableStateOf');
  lines.push('import androidx.compose.runtime.setValue');
  if (collections.length > 0) {
    lines.push('import kotlinx.coroutines.CoroutineScope');
    lines.push('import kotlinx.coroutines.Dispatchers');
    lines.push('import kotlinx.coroutines.Job');
    lines.push('import kotlinx.coroutines.launch');
    lines.push(`import ${packageName}.collections.*`);
  }
  lines.push('');

  lines.push('object DesignSystemController {');
  lines.push('    val instance get() = this');
  lines.push('');

  if (collections.length > 0) {
    lines.push('    private val coroutineScope = CoroutineScope(Dispatchers.Main.immediate + Job())');
    lines.push('');
  }

  lines.push('    var defaultDurationMillis: Int by mutableIntStateOf(0)');
  lines.push('');
  lines.push('    fun setAnimationDuration(durationMillis: Int) {');
  lines.push('        defaultDurationMillis = durationMillis');
  lines.push('    }');
  lines.push('');

  for (const col of collections) {
    const defaultMode =
      col.modes.length > 0
        ? col.modes[col.defaultModeIndex] ?? col.modes[0]
        : undefined;
    const defaultModePascal = defaultMode
      ? escapeKotlinIdentifier(defaultMode.pascalName)
      : 'Default';
    const defaultModeVal = defaultMode
      ? escapeKotlinIdentifier(`${defaultMode.pascalName}${col.className}`)
      : `${col.className}()`;

    lines.push(`    // --- ${col.className} ---`);
    lines.push(`    private var _${col.accessor}Job: Job? = null`);
    lines.push('');
    lines.push(
      `    var current${col.className}Mode: ${col.className}Mode by mutableStateOf(${col.className}Mode.${defaultModePascal})`,
    );
    lines.push('        internal set');
    lines.push('');
    lines.push(
      `    var ${col.accessor}: ${col.className} by mutableStateOf(${defaultModeVal})`,
    );
    lines.push('        internal set');
    lines.push('');

    // resolve method
    lines.push(
      `    fun resolve${col.className}(mode: ${col.className}Mode): ${col.className} = when (mode) {`,
    );
    if (col.modes.length === 0) {
      lines.push(`        ${col.className}Mode.Default -> ${col.className}()`);
    } else {
      for (const mode of col.modes) {
        const modeEnum = `${col.className}Mode.${escapeKotlinIdentifier(mode.pascalName)}`;
        const modeVal = escapeKotlinIdentifier(`${mode.pascalName}${col.className}`);
        lines.push(`        ${modeEnum} -> ${modeVal}`);
      }
    }
    lines.push('    }');
    lines.push('');

    // setter method with optional lerp
    lines.push(`    fun set${col.className}Mode(`);
    lines.push(`        mode: ${col.className}Mode,`);
    lines.push('        durationMillis: Int = defaultDurationMillis,');
    lines.push('    ) {');
    lines.push(
      `        if (mode == current${col.className}Mode && durationMillis <= 0) return`,
    );
    lines.push(`        current${col.className}Mode = mode`);
    lines.push(`        val target = resolve${col.className}(mode)`);
    lines.push('        if (durationMillis <= 0) {');
    lines.push(`            _${col.accessor}Job?.cancel()`);
    lines.push(`            _${col.accessor}Job = null`);
    lines.push(`            ${col.accessor} = target`);
    lines.push('        } else {');
    lines.push(`            val start = ${col.accessor}`);
    lines.push(`            _${col.accessor}Job?.cancel()`);
    lines.push(`            _${col.accessor}Job = coroutineScope.launch {`);
    lines.push('                val anim = Animatable(0f)');
    lines.push('                anim.animateTo(');
    lines.push('                    targetValue = 1f,');
    lines.push('                    animationSpec = tween(durationMillis = durationMillis),');
    lines.push('                ) {');
    lines.push(
      `                    ${col.accessor} = ${col.className}.lerp(start, target, value)`,
    );
    lines.push('                }');
    lines.push(`                ${col.accessor} = target`);
    lines.push('            }');
    lines.push('        }');
    lines.push('    }');
    lines.push('');
  }

  // resetForTest
  lines.push('    fun resetForTest() {');
  lines.push('        defaultDurationMillis = 0');
  for (const col of collections) {
    const defaultMode =
      col.modes.length > 0
        ? col.modes[col.defaultModeIndex] ?? col.modes[0]
        : undefined;
    const defaultModePascal = defaultMode
      ? escapeKotlinIdentifier(defaultMode.pascalName)
      : 'Default';
    const defaultModeVal = defaultMode
      ? escapeKotlinIdentifier(`${defaultMode.pascalName}${col.className}`)
      : `${col.className}()`;

    lines.push(`        _${col.accessor}Job?.cancel()`);
    lines.push(`        _${col.accessor}Job = null`);
    lines.push(
      `        current${col.className}Mode = ${col.className}Mode.${defaultModePascal}`,
    );
    lines.push(`        ${col.accessor} = ${defaultModeVal}`);
  }
  lines.push('    }');
  lines.push('}');
  lines.push('');

  return {
    path: `src/main/kotlin/${packagePath}/theme/DesignSystemController.kt`,
    contents: lines.join('\n').trimEnd() + '\n',
  };
}

// ============================================================================
// 3. Theme.kt
// ============================================================================

function emitThemeFile(
  collections: ReadonlyArray<PreparedComposeCollection>,
  packagePath: string,
  packageName: string,
): EmittedFile {
  const lines: string[] = [
    '// GENERATED FILE — do not edit by hand.',
    '// Generated by Varcast.',
    '',
    `package ${packageName}.theme`,
    '',
    'import androidx.compose.runtime.Composable',
    'import androidx.compose.runtime.CompositionLocalProvider',
    'import androidx.compose.runtime.ReadOnlyComposable',
    'import androidx.compose.runtime.staticCompositionLocalOf',
  ];

  if (collections.length > 0) {
    lines.push(`import ${packageName}.collections.*`);
  }
  lines.push(`import ${packageName}.composites.DSColorStyles`);
  lines.push(`import ${packageName}.composites.DSTextStyles`);
  lines.push(`import ${packageName}.composites.DSShadows`);
  lines.push('');

  // 1. Composition Locals
  lines.push('// ============================================================================');
  lines.push('// 1. CompositionLocals');
  lines.push('// ============================================================================');
  lines.push('');

  for (const col of collections) {
    lines.push(
      `val Local${col.className} = staticCompositionLocalOf<${col.className}> {`,
    );
    lines.push(
      `    error("No ${col.className} provided. Make sure to wrap your composables in DesignSystemTheme.")`,
    );
    lines.push('}');
    lines.push('');
  }

  lines.push('val LocalDSColorStyles = staticCompositionLocalOf<DSColorStyles> {');
  lines.push('    DSColorStyles');
  lines.push('}');
  lines.push('');
  lines.push('val LocalDSTextStyles = staticCompositionLocalOf<DSTextStyles> {');
  lines.push('    DSTextStyles');
  lines.push('}');
  lines.push('');
  lines.push('val LocalDSShadows = staticCompositionLocalOf<DSShadows> {');
  lines.push('    DSShadows');
  lines.push('}');
  lines.push('');

  // 2. DesignSystemTheme Composable
  lines.push('// ============================================================================');
  lines.push('// 2. DesignSystemTheme Composable');
  lines.push('// ============================================================================');
  lines.push('');
  lines.push('@Composable');
  lines.push('fun DesignSystemTheme(');
  for (const col of collections) {
    lines.push(
      `    ${col.accessor}: ${col.className} = DesignSystemController.${col.accessor},`,
    );
  }
  lines.push('    content: @Composable () -> Unit,');
  lines.push(') {');
  lines.push('    CompositionLocalProvider(');
  for (const col of collections) {
    lines.push(`        Local${col.className} provides ${col.accessor},`);
  }
  lines.push('        LocalDSColorStyles provides DSColorStyles,');
  lines.push('        LocalDSTextStyles provides DSTextStyles,');
  lines.push('        LocalDSShadows provides DSShadows,');
  lines.push('    ) {');
  lines.push('        content()');
  lines.push('    }');
  lines.push('}');
  lines.push('');

  // 3. DesignSystemTheme Accessor Object
  lines.push('// ============================================================================');
  lines.push('// 3. DesignSystemTheme Accessor Object');
  lines.push('// ============================================================================');
  lines.push('');
  lines.push('object DesignSystemTheme {');

  for (const col of collections) {
    lines.push(`    val ${col.accessor}: ${col.className}`);
    lines.push('        @Composable');
    lines.push('        @ReadOnlyComposable');
    lines.push(`        get() = Local${col.className}.current`);
    lines.push('');
  }

  emitCollectionAliases(collections, lines, 'theme');

  lines.push('    val colorStyles: DSColorStyles');
  lines.push('        @Composable');
  lines.push('        @ReadOnlyComposable');
  lines.push('        get() = LocalDSColorStyles.current');
  lines.push('');
  lines.push('    val textStyles: DSTextStyles');
  lines.push('        @Composable');
  lines.push('        @ReadOnlyComposable');
  lines.push('        get() = LocalDSTextStyles.current');
  lines.push('');
  lines.push('    val shadows: DSShadows');
  lines.push('        @Composable');
  lines.push('        @ReadOnlyComposable');
  lines.push('        get() = LocalDSShadows.current');
  lines.push('}');
  lines.push('');

  return {
    path: `src/main/kotlin/${packagePath}/theme/Theme.kt`,
    contents: lines.join('\n').trimEnd() + '\n',
  };
}

// ============================================================================
// 4. AppTheme.kt
// ============================================================================

function emitAppThemeFile(
  collections: ReadonlyArray<PreparedComposeCollection>,
  packagePath: string,
  packageName: string,
): EmittedFile {
  const lines: string[] = [
    '// GENERATED FILE — do not edit by hand.',
    '// Generated by Varcast.',
    '',
    `package ${packageName}.theme`,
    '',
  ];

  if (collections.length > 0) {
    lines.push(`import ${packageName}.collections.*`);
  }
  lines.push(`import ${packageName}.composites.DSColorStyles`);
  lines.push(`import ${packageName}.composites.DSTextStyles`);
  lines.push(`import ${packageName}.composites.DSShadows`);
  lines.push('');

  lines.push('object AppTheme {');
  lines.push('    // --- Direct Token Accessors ---');

  for (const col of collections) {
    lines.push(`    val ${col.accessor}: ${col.className}`);
    lines.push(`        get() = DesignSystemController.${col.accessor}`);
    lines.push('');
  }

  emitCollectionAliases(collections, lines, 'app');

  lines.push('    // --- Composite Styles ---');
  lines.push('    val colorStyles: DSColorStyles = DSColorStyles');
  lines.push('    val textStyles: DSTextStyles = DSTextStyles');
  lines.push('    val shadows: DSShadows = DSShadows');
  lines.push('');

  if (collections.length > 0) {
    lines.push('    // --- Mode Management ---');
    for (const col of collections) {
      lines.push(
        `    val current${col.className}Mode: ${col.className}Mode`,
      );
      lines.push(
        `        get() = DesignSystemController.current${col.className}Mode`,
      );
      lines.push('');
      lines.push(
        `    fun get${col.className}Mode(): ${col.className}Mode =`,
      );
      lines.push(
        `        DesignSystemController.current${col.className}Mode`,
      );
      lines.push('');
      lines.push(`    fun set${col.className}Mode(`);
      lines.push(`        mode: ${col.className}Mode,`);
      lines.push(
        '        durationMillis: Int = DesignSystemController.defaultDurationMillis,',
      );
      lines.push('    ) {');
      lines.push(
        `        DesignSystemController.set${col.className}Mode(mode, durationMillis)`,
      );
      lines.push('    }');
      lines.push('');
    }
  }

  lines.push('    // --- Animation Duration ---');
  lines.push('    var defaultDurationMillis: Int');
  lines.push('        get() = DesignSystemController.defaultDurationMillis');
  lines.push('        set(value) {');
  lines.push('            DesignSystemController.defaultDurationMillis = value');
  lines.push('        }');
  lines.push('');
  lines.push('    fun setAnimationDuration(durationMillis: Int) {');
  lines.push('        DesignSystemController.setAnimationDuration(durationMillis)');
  lines.push('    }');
  lines.push('');
  lines.push('    // --- Testing Support ---');
  lines.push('    fun resetForTest() {');
  lines.push('        DesignSystemController.resetForTest()');
  lines.push('    }');
  lines.push('}');
  lines.push('');

  return {
    path: `src/main/kotlin/${packagePath}/theme/AppTheme.kt`,
    contents: lines.join('\n').trimEnd() + '\n',
  };
}

// ============================================================================
// Helpers
// ============================================================================

function emitCollectionAliases(
  collections: ReadonlyArray<PreparedComposeCollection>,
  lines: string[],
  context: 'theme' | 'app',
): void {
  const existingAccessors = new Set(collections.map((c) => c.accessor));

  // Common convenient aliases: colorTokens -> colors, spacingTokens -> spacing, typographyTokens -> typography
  const aliasMap: Record<string, string> = {
    colorTokens: 'colors',
    spacingTokens: 'spacing',
    typographyTokens: 'typography',
  };

  for (const col of collections) {
    const alias = aliasMap[col.accessor];
    if (alias && !existingAccessors.has(alias)) {
      existingAccessors.add(alias);
      if (context === 'theme') {
        lines.push(`    val ${alias}: ${col.className}`);
        lines.push('        @Composable');
        lines.push('        @ReadOnlyComposable');
        lines.push(`        get() = ${col.accessor}`);
        lines.push('');
      } else {
        lines.push(`    val ${alias}: ${col.className}`);
        lines.push(`        get() = ${col.accessor}`);
        lines.push('');
      }
    }
  }
}
