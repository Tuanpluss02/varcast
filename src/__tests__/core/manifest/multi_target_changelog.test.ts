import { describe, it, expect } from 'vitest';
import { generateMultiTargetChangelog } from '../../../core/manifest';
import type { ManifestDiff } from '../../../core/manifest';

describe('generateMultiTargetChangelog', () => {
  function createEmptyDiff(targetId: string): ManifestDiff {
    return {
      targetId,
      variables: { added: [], removed: [], renamed: [] },
      collections: { added: [], removed: [], renamed: [] },
      composites: { added: [], removed: [], renamed: [] },
    };
  }

  const flutterDiff: ManifestDiff = {
    targetId: 'flutter',
    variables: {
      added: [{ id: 'v1', name: 'colorBg', figmaName: 'color/bg' }],
      removed: [],
      renamed: [],
    },
    collections: { added: [], removed: [], renamed: [] },
    composites: { added: [], removed: [], renamed: [] },
  };

  const rnDiff: ManifestDiff = {
    targetId: 'react_native',
    variables: {
      added: [],
      removed: [{ id: 'v2', name: 'oldHeader', figmaName: 'header/old' }],
      renamed: [
        {
          id: 'v3',
          name: 'buttonPrimary',
          oldFigmaName: 'btn/primary',
          newFigmaName: 'button/primary',
        },
      ],
    },
    collections: { added: [], removed: [], renamed: [] },
    composites: { added: [], removed: [], renamed: [] },
  };

  describe('empty diffs', () => {
    it('returns standard no changes header when input is empty object', () => {
      const result = generateMultiTargetChangelog({});
      expect(result).toBe(
        '# Changelog\n\nGenerated by Varcast. Do not edit by hand.\n\nNo changes.',
      );
    });

    it('returns standard no changes header when single target has no changes', () => {
      const result = generateMultiTargetChangelog({
        flutter: createEmptyDiff('flutter'),
      });
      expect(result).toBe(
        '# Changelog\n\nGenerated by Varcast. Do not edit by hand.\n\nNo changes.',
      );
      expect(result).not.toContain('## Target:');
    });

    it('renders target sections with No changes. when multi-target has no changes', () => {
      const result = generateMultiTargetChangelog({
        flutter: createEmptyDiff('flutter'),
        react_native: createEmptyDiff('react_native'),
      });
      expect(result).toContain('# Design System Tokens Changelog');
      expect(result).toContain('## Target: flutter\n\nNo changes.');
      expect(result).toContain('## Target: react_native\n\nNo changes.');
    });
  });

  describe('single-target diff output', () => {
    it('renders single-target diff cleanly with ## Added and does not contain ## Target:', () => {
      const result = generateMultiTargetChangelog({ flutter: flutterDiff });
      expect(result).toContain('# Changelog');
      expect(result).toContain('## Added');
      expect(result).toContain('### Variables');
      expect(result).toContain('- `colorBg` — color/bg');
      expect(result).not.toContain('## Target:');
    });
  });

  describe('multi-target diff output', () => {
    it('renders multi-target diffs with header and separate target sections', () => {
      const result = generateMultiTargetChangelog({
        flutter: flutterDiff,
        react_native: rnDiff,
      });

      expect(result).toContain('# Design System Tokens Changelog');
      expect(result).toContain('Generated by Varcast. Do not edit by hand.');

      expect(result).toContain('## Target: flutter');
      expect(result).toContain('## Target: react_native');

      // Flutter content under flutter target
      expect(result).toContain('colorBg');
      expect(result).toContain('color/bg');

      // React Native content under react_native target
      expect(result).toContain('oldHeader');
      expect(result).toContain('buttonPrimary');
      expect(result).toContain('`buttonPrimary`: `btn/primary` → `button/primary`');
    });

    it('renders targets in sorted key order regardless of input key order', () => {
      const result = generateMultiTargetChangelog({
        react_native: rnDiff,
        flutter: flutterDiff,
      });

      const flutterIdx = result.indexOf('## Target: flutter');
      const rnIdx = result.indexOf('## Target: react_native');
      expect(flutterIdx).toBeGreaterThan(-1);
      expect(rnIdx).toBeGreaterThan(-1);
      expect(flutterIdx).toBeLessThan(rnIdx);
    });

    it('handles one target with changes and another without changes cleanly', () => {
      const result = generateMultiTargetChangelog({
        flutter: flutterDiff,
        react_native: createEmptyDiff('react_native'),
      });

      expect(result).toContain('## Target: flutter');
      expect(result).toContain('colorBg');
      expect(result).toContain('## Target: react_native\n\nNo changes.');
    });
  });
});
