import type {
  ManifestDiff,
  ManifestItemDiff,
  ManifestRenameDiff,
} from './types';

function renderDiffSections(
  diff: ManifestDiff,
  headingLevel: number = 2,
): string[] {
  const lines: string[] = [];

  const variables = diff.variables ?? {
    added: diff.added ?? [],
    removed: diff.removed ?? [],
    renamed: diff.renamed ?? [],
  };
  const collections = diff.collections ?? {
    added: [],
    removed: [],
    renamed: [],
  };
  const composites = diff.composites ?? {
    added: [],
    removed: [],
    renamed: [],
  };

  const hasAdded =
    variables.added.length > 0 ||
    collections.added.length > 0 ||
    composites.added.length > 0;
  const hasRemoved =
    variables.removed.length > 0 ||
    collections.removed.length > 0 ||
    composites.removed.length > 0;
  const hasRenamed =
    variables.renamed.length > 0 ||
    collections.renamed.length > 0 ||
    composites.renamed.length > 0;

  if (!hasAdded && !hasRemoved && !hasRenamed) {
    return [];
  }

  const hMajor = '#'.repeat(headingLevel);
  const hMinor = '#'.repeat(headingLevel + 1);

  const renderItems = (title: string, items: ManifestItemDiff[]) => {
    if (items.length === 0) return;
    lines.push(`${hMinor} ${title}`);
    for (const item of items) {
      lines.push(
        `- \`${item.name}\`${item.figmaName ? ` — ${item.figmaName}` : ''}`,
      );
    }
    lines.push('');
  };

  const renderRenames = (title: string, items: ManifestRenameDiff[]) => {
    if (items.length === 0) return;
    lines.push(`${hMinor} ${title}`);
    for (const item of items) {
      lines.push(
        `- \`${item.name}\`: \`${item.oldFigmaName}\` → \`${item.newFigmaName}\``,
      );
    }
    lines.push('');
  };

  if (hasAdded) {
    lines.push(`${hMajor} Added`);
    lines.push('');
    renderItems('Variables', variables.added);
    renderItems('Collections', collections.added);
    renderItems('Composites', composites.added);
  }

  if (hasRemoved) {
    lines.push(`${hMajor} Removed`);
    lines.push('');
    renderItems('Variables', variables.removed);
    renderItems('Collections', collections.removed);
    renderItems('Composites', composites.removed);
  }

  if (hasRenamed) {
    lines.push(`${hMajor} Renamed`);
    lines.push('');
    renderRenames('Variables', variables.renamed);
    renderRenames('Collections', collections.renamed);
    renderRenames('Composites', composites.renamed);
  }

  return lines;
}

/**
 * Generates a clean, target-agnostic markdown changelog from a ManifestDiff.
 */
export function generateChangelog(diff: ManifestDiff): string {
  const lines: string[] = [];
  lines.push('# Changelog');
  lines.push('');
  lines.push('Generated by Varcast. Do not edit by hand.');
  lines.push('');

  const sections = renderDiffSections(diff, 2);
  if (sections.length === 0) {
    lines.push('No changes.');
    return lines.join('\n');
  }

  lines.push(...sections);
  return lines.join('\n').trimEnd();
}

/**
 * Generates a consolidated changelog across multiple targets.
 * - If empty: emits standard empty changelog.
 * - If single target: delegates to generateChangelog.
 * - If multiple targets: emits unified changelog with sorted per-target sections.
 */
export function generateMultiTargetChangelog(
  diffsByTarget: Record<string, ManifestDiff>,
): string {
  const targetIds = Object.keys(diffsByTarget).sort();
  if (targetIds.length === 0) {
    return '# Changelog\n\nGenerated by Varcast. Do not edit by hand.\n\nNo changes.';
  }

  if (targetIds.length === 1) {
    return generateChangelog(diffsByTarget[targetIds[0]]);
  }

  const lines: string[] = [];
  lines.push('# Design System Tokens Changelog');
  lines.push('');
  lines.push('Generated by Varcast. Do not edit by hand.');
  lines.push('');

  for (let i = 0; i < targetIds.length; i++) {
    const targetId = targetIds[i];
    const diff = diffsByTarget[targetId];
    lines.push(`## Target: ${targetId}`);
    lines.push('');

    const sections = renderDiffSections(diff, 3);
    if (sections.length === 0) {
      lines.push('No changes.');
    } else {
      lines.push(...sections);
    }

    if (i < targetIds.length - 1) {
      if (lines[lines.length - 1] !== '') {
        lines.push('');
      }
    }
  }

  return lines.join('\n').trimEnd();
}
