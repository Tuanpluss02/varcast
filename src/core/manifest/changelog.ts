import type {
  ManifestDiff,
  ManifestItemDiff,
  ManifestRenameDiff,
} from './types';

/**
 * Generates a clean, target-agnostic markdown changelog from a ManifestDiff.
 */
export function generateChangelog(diff: ManifestDiff): string {
  const lines: string[] = [];
  lines.push('# Changelog');
  lines.push('');
  lines.push('Generated by Varcast. Do not edit by hand.');
  lines.push('');

  const variables = diff.variables ?? {
    added: diff.added ?? [],
    removed: diff.removed ?? [],
    renamed: diff.renamed ?? [],
  };
  const collections = diff.collections ?? {
    added: [],
    removed: [],
    renamed: [],
  };
  const composites = diff.composites ?? {
    added: [],
    removed: [],
    renamed: [],
  };

  const hasAdded =
    variables.added.length > 0 ||
    collections.added.length > 0 ||
    composites.added.length > 0;
  const hasRemoved =
    variables.removed.length > 0 ||
    collections.removed.length > 0 ||
    composites.removed.length > 0;
  const hasRenamed =
    variables.renamed.length > 0 ||
    collections.renamed.length > 0 ||
    composites.renamed.length > 0;

  if (!hasAdded && !hasRemoved && !hasRenamed) {
    lines.push('No changes.');
    return lines.join('\n');
  }

  const renderItems = (title: string, items: ManifestItemDiff[]) => {
    if (items.length === 0) return;
    lines.push(`### ${title}`);
    for (const item of items) {
      lines.push(
        `- \`${item.name}\`${item.figmaName ? ` — ${item.figmaName}` : ''}`,
      );
    }
    lines.push('');
  };

  const renderRenames = (title: string, items: ManifestRenameDiff[]) => {
    if (items.length === 0) return;
    lines.push(`### ${title}`);
    for (const item of items) {
      lines.push(
        `- \`${item.name}\`: \`${item.oldFigmaName}\` → \`${item.newFigmaName}\``,
      );
    }
    lines.push('');
  };

  if (hasAdded) {
    lines.push('## Added');
    lines.push('');
    renderItems('Variables', variables.added);
    renderItems('Collections', collections.added);
    renderItems('Composites', composites.added);
  }

  if (hasRemoved) {
    lines.push('## Removed');
    lines.push('');
    renderItems('Variables', variables.removed);
    renderItems('Collections', collections.removed);
    renderItems('Composites', composites.removed);
  }

  if (hasRenamed) {
    lines.push('## Renamed');
    lines.push('');
    renderRenames('Variables', variables.renamed);
    renderRenames('Collections', collections.renamed);
    renderRenames('Composites', composites.renamed);
  }

  return lines.join('\n').trimEnd();
}
